TOP, BOT = 1, 11        # keycap rows (inclusive) inside the 13-row cell, like the DS icons
LABEL_Y = 4             # first label row

KEYCAP_L, KEYCAP_R = 0xE100, 0xE17F
ARROW_CODES = {'left': 0xE180, 'right': 0xE181, 'up': 0xE182, 'down': 0xE183}
PS_CODES = {'cross': 0xE190, 'circle': 0xE191, 'square': 0xE192, 'triangle': 0xE193}


def glyphs():
    """code -> (rows: list of 13 strings of '#'/'.', glyph_width, advance)"""
    out = {}
    blank = lambda w: [['.'] * w for _ in range(13)]

    # The game advances by char_width + 1, so pieces of one keycap use char_width = width - 1
    # to join up; the right edge keeps the extra pixel as the gap after the key.
    def put(code, g, adv=None):
        out[code] = ([''.join(r) for r in g], len(g[0]), len(g[0]) - 1 if adv is None else adv)

    # left edge: 2 columns, rounded
    g = blank(2)
    for y in range(TOP, BOT + 1):
        g[y][1] = '#'
        if TOP < y < BOT:
            g[y][0] = '#'
    put(KEYCAP_L, g)
    # right edge: 1 padding column + 2 edge columns; advance leaves a 1px gap after the key
    g = blank(3)
    for y in range(TOP, BOT + 1):
        g[y][0] = g[y][1] = '#'
        if TOP < y < BOT:
            g[y][2] = '#'
    put(KEYCAP_R, g, 3)

    def middle(code, bitmap):
        w = len(bitmap[0]) + 1  # 1 column of key before the character
        g = blank(w)
        for y in range(TOP, BOT + 1):
            for x in range(w):
                g[y][x] = '#'
        for yy, row in enumerate(bitmap):
            for xx, c in enumerate(row):
                if c == '#':
                    g[LABEL_Y + yy][1 + xx] = '.'
        put(code, g)

    for ch, bm in FONT.items():
        middle(0xE100 + ord(ch), bm)
        if 'A' <= ch <= 'Z':
            middle(0xE100 + ord(ch.lower()), bm)
    for name, bm in ARROWS.items():
        middle(ARROW_CODES[name], bm)
    for name, bm in PS.items():
        g = blank(11)
        for yy, row in enumerate(DISC):
            for xx, c in enumerate(row):
                if c == '.':
                    g[TOP + yy][xx] = '#'
        for yy, row in enumerate(bm):
            for xx, c in enumerate(row):
                if c == '#':
                    g[LABEL_Y + yy][3 + xx] = '.'
        put(PS_CODES[name], g, 11)
    return out


def add_to_nftr(raw):
    """Append the prompt glyphs to an NFTR font (new CGLP entries, one new CWDH and CMAP block)."""
    sys.path.insert(0, os.path.dirname(__file__))
    from nftr import NFTR
    f = NFTR(raw)
    assert f.bpp == 1 and f.cell_w == 11 and f.cell_h == 13
    gl = glyphs()
    codes = sorted(c for c in gl if c not in f.cmap)
    assert not any(codes[0] <= c <= codes[-1] for c in f.cmap), 'prompt glyph range overlaps the font'
    first = f.nglyphs
    # glyph bitmaps, 1bpp row-major MSB first, cell_size bytes each
    data = bytearray()
    for c in codes:
        rows, gw, adv = gl[c]
        bits = []
        for y in range(13):
            r = rows[y].ljust(11, '.')
            bits += [1 if ch == '#' else 0 for ch in r[:11]]
        cell = bytearray(f.cell_size)
        for i, b in enumerate(bits):
            if b:
                cell[i >> 3] |= 0x80 >> (i & 7)
        data += cell
    cglp_off = f.cglp_ptr - 8
    cglp_size = struct.unpack_from('<I', raw, cglp_off + 4)[0]
    ins_at = cglp_off + cglp_size
    pad = (-len(data)) % 4
    ins = bytes(data) + bytes(pad)
    out = bytearray(raw[:ins_at]) + ins + bytearray(raw[ins_at:])
    delta = len(ins)
    struct.pack_into('<I', out, cglp_off + 4, cglp_size + delta)

    def fix(off):  # pointer field at `off` (already in the new layout)
        v = struct.unpack_from('<I', out, off)[0]
        if v and v - 8 >= ins_at:
            struct.pack_into('<I', out, off, v + delta)

    fp = f.blocks[b'FINF'][0][0]
    fix(fp + 0x14); fix(fp + 0x18)  # CWDH, CMAP pointers (CGLP is before the insertion)
    # walk CWDH and CMAP chains in the new layout and fix their next pointers
    last_cwdh = None
    p = struct.unpack_from('<I', out, fp + 0x14)[0] - 8
    while True:
        fix(p + 12); last_cwdh = p
        nxt = struct.unpack_from('<I', out, p + 12)[0]
        if not nxt: break
        p = nxt - 8
    p = struct.unpack_from('<I', out, fp + 0x18)[0] - 8
    while True:
        fix(p + 16)
        nxt = struct.unpack_from('<I', out, p + 16)[0]
        if not nxt: break
        p = nxt - 8
    # new CWDH block: glyphs first .. first+n-1
    n = len(codes)
    body = bytearray()
    for c in codes:
        rows, gw, adv = gl[c]
        body += struct.pack('<bBB', 0, gw, adv)
    blk = bytearray(b'HDWC') + struct.pack('<I', 0) + struct.pack('<HHI', first, first + n - 1, 0) + body
    blk += bytes((-len(blk)) % 4)
    struct.pack_into('<I', blk, 4, len(blk))
    cwdh_new = len(out)
    out += blk
    struct.pack_into('<I', out, last_cwdh + 12, cwdh_new + 8)
    # new CMAP block, type 2 (scan): pairs code -> glyph
    body = struct.pack('<H', n) + b''.join(struct.pack('<HH', c, first + i) for i, c in enumerate(codes))
    blk = bytearray(b'PAMC') + struct.pack('<I', 0) + struct.pack('<HHHxxI', codes[0], codes[-1], 2, 0) + body
    blk += bytes((-len(blk)) % 4)
    struct.pack_into('<I', blk, 4, len(blk))
    # The game (NNS) stops at the first CMAP block whose code range covers a character, and the
    # font's big scan block spans the private-use area: put this block first in the chain.
    cmap_new = len(out)
    first_cmap = struct.unpack_from('<I', out, fp + 0x18)[0]
    struct.pack_into('<I', blk, 16, first_cmap)
    out += blk
    struct.pack_into('<I', out, fp + 0x18, cmap_new + 8)
    struct.pack_into('<I', out, 8, len(out))
    nblocks = struct.unpack_from('<H', out, 0xE)[0]
    struct.pack_into('<H', out, 0xE, nblocks + 2)
    return bytes(out)


def write_inc(path):
    """C++ tables for the port's HUD icon renderer."""
    lines = ['// generated by tools/promptfont.py - do not edit', '#pragma once', '#include <cstdint>', '',
             'struct PromptChar { char c; uint8_t w; uint8_t rows[5]; };',
             'static const PromptChar kPromptFont[] = {']
    for ch, bm in sorted(FONT.items()):
        rows = [int(r.replace('#', '1').replace('.', '0')[::-1] or '0', 2) for r in bm]
        esc = {'\\': '\\\\', "'": "\\'"}.get(ch, ch)
        if ord(ch) < 32: esc = '\\x%02x' % ord(ch)
        lines.append("    {'%s', %d, {%s}}," % (esc, len(bm[0]), ', '.join('0x%02x' % r for r in rows)))
    lines.append('};')
    lines.append('static const PromptChar kPromptArrows[4] = {  // left, right, up, down')
    for name in ('left', 'right', 'up', 'down'):
        rows = [int(r.replace('#', '1').replace('.', '0')[::-1], 2) for r in ARROWS[name]]
        lines.append("    {'%s', 5, {%s}}," % (name[0], ', '.join('0x%02x' % r for r in rows)))
    lines.append('};')
    lines.append('static const PromptChar kPromptPS[4] = {  // cross, circle, square, triangle')
    for name in ('cross', 'circle', 'square', 'triangle'):
        rows = [int(r.replace('#', '1').replace('.', '0')[::-1], 2) for r in PS[name]]
        lines.append("    {'%s', 5, {%s}}," % (name[0], ', '.join('0x%02x' % r for r in rows)))
    lines.append('};')
    open(path, 'w', newline='\n').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    write_inc(os.path.join(ROOT, 'port', 'src', 'promptfont.inc'))
    print('wrote port/src/promptfont.inc')
