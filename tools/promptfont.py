"""Button-prompt glyphs for the PC port: keycaps and controller buttons drawn in the style of the
game's own button icons (U+E000-E01C), so prompts can name whatever key or button is bound.

The glyphs live in the private-use range and are appended to the game font by build_english.py:
  U+E100            keycap left edge
  U+E100 + c        keycap middle showing ASCII character c (0x21-0x7E, lower case drawn as upper)
  U+E17F            keycap right edge
  U+E180-E183       keycap middle with an arrow: left, right, up, down
  U+E190-E193       PlayStation face buttons: cross, circle, square, triangle
A keycap is spelled  E100, middles..., E17F  and renders as one filled key with the label cut out,
like the DS [L] icon. The same 5-pixel label font is used by the port to redraw HUD icons
(port/src/promptfont.inc, generated by `python tools/promptfont.py`).
"""
